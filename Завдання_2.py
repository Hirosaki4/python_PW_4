# Дані про товари (можна зробити циклом, тут — приклад)
products = [
    ("Кава", 99.99, 3),
    ("Чай", 59.50, 5),
    ("Шоколад", 42.75, 10)
]

# Заголовок таблиці
print("{:<20} {:>10} {:^8}".format("Назва товару", "Ціна", "К-сть"))
print("-" * 40)

# Виведення кожного товару
for name, price, quantity in products:
    print("{:<20} {:>10.2f} {:^8}".format(name, price, quantity))
